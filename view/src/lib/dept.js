/* 진료과 이름.
 *
 * 서버는 account.role 의 **코드**를 그대로 준다(primary_staff_dept).
 * 한글 표기는 여기서 만든다 — 서버가 한글을 들고 있으면 표기 하나
 * 바꾸는 데 배포를 해야 한다. 역할이 여섯으로 고정이라 표가 커지지도
 * 않는다.
 *
 * ⚠ role 은 「역할」이지 「진료과」가 아니다.
 *   surgery 는 외과이고, **유방외과 같은 세부 분과는 이 값으로
 *   구분되지 않는다.** 전에 화면에 「유방외과」로 나오던 자리가
 *   「외과」가 된다. 세부 분과를 내려면 서버에 칸이 하나 더 있어야
 *   한다 — 팀에 확인 중이다.
 */
const DEPT = {
  surgery:   "외과",
  radiology: "영상의학과",
  pathology: "병리과",
  nursing:   "간호과",
  reception: "원무과",
  admin:     "관리부",
};

/** 코드를 사람이 읽는 말로. 낼 것이 없으면 빈 문자열이다.
 *
 * 표에 없는 값이 오면 두 갈래로 나뉜다.
 *
 *   · **한글이면 그대로 낸다.** 이미 사람이 읽을 말이다. 아직 코드로
 *     안 바뀐 칸(last_visit_dept 같은 것)이 여기로 온다
 *   · **영문이면 감춘다.** 환자에게 「oncology」는 아무 뜻도 아니다.
 *     빈칸이 낫다
 *
 * 뒤쪽은 대가가 있다 — 역할이 새로 생기면 화면에서 조용히 사라진다.
 * 여섯으로 고정이라는 전제 위에 둔 선택이고, 늘어나면 이 표에
 * 한 줄 더하면 된다.
 */
export function deptLabel(v) {
  if (!v) return "";
  if (DEPT[v]) return DEPT[v];
  return /[가-힣]/.test(v) ? v : "";
}

/** 「 · 외과」처럼 앞에 가운뎃점을 붙여 잇는다. 낼 것이 없으면 빈 문자열.
 *  화면 세 곳이 똑같이 쓰던 삼항 연산을 여기로 모았다. */
export function deptSuffix(v) {
  const t = deptLabel(v);
  return t ? ` · ${t}` : "";
}
