# 모델이 지킬 규칙. 매 요청 같은 값이 들어간다.
#
# 「엮는다」가 아니라 「쓴다」인 것이 핵심이다. 완성된 문장을 주고 "보태지 마라 ·
# 해석하지 마라 · 수치 바꾸지 마라"고 하면 베끼는 것이 모든 규칙을 만족한다.
# 09-08 실측 — 완성 문장을 주면 온도 0 에서 50회 전부 뼈대와 글자까지 같았다.
# 판독값만 주니 어미와 연결을 다시 썼고 수치는 150회 전부 보존됐다.
#
# 09-10 병리 회귀 — 「번호가 붙은 항목은」이 조건 없이 읽혀서, 병변이 없는
# 병리 표 9줄에 모델이 「병변 1~9」를 지어 붙였다. 조건문으로 바꾸고 번호를
# 만들지 말라는 줄을 더한다. 수치 검사는 숫자만 보므로 이걸 못 잡는다.
#
# 근거 표시([[e:ID]]) 규칙은 두지 않는다. 화면이 마스크·수치를 따로 보여주므로
# 문장별 근거가 필요 없고, 그 규칙이 있으면 4B 모델이 문장 짓는 일을 놓친다.
SYSTEM = """아래 판독값을 읽고 의사에게 보낼 소견문을 쓴다.
읽기 좋게 서술한다. 관련된 값끼리 한 문장에 묶되,
판독값에 「병변 1」처럼 번호가 붙어 있으면 항목마다 문장을 끊는다.
판독값에 없는 번호를 새로 붙이지 않는다.

지키는 것
  수치는 표기까지 그대로 옮긴다. 반올림하거나 단위를 바꾸지 않는다.
  판독값에 없는 소견을 지어내지 않는다.
  수치가 무엇을 뜻하는지 해석하지 않는다.
  악성 여부를 말하지 않는다.
  존댓말로 쓴다.
  머리말 없이 소견부터 쓴다. 환자나 독자를 부르지 않는다."""

# 응답 형식 강제. 이게 없으면 모델이 생각 과정과 머리말을 같이 뱉는다.
# 필드가 「소견」 하나뿐인 이유 — 안내는 코드가 쓰고 모델을 거치지 않는다.
SCHEMA = {
    "type": "object",
    "properties": {"소견": {"type": "string"}},
    "required": ["소견"],
}

def build(pairs: list[tuple[str, str]]) -> str :
    """모델에 넘길 프롬프트. 판독값 표 하나뿐이다.

    안내(notes)는 넘기지 않는다 — 우리가 쓴 문장이 그대로 나가야 한다.

    이름을 자리맞춤한 꼴로 09-08 시험을 했다. 표 모양을 바꾸면
    50회 재현성 시험을 다시 돌린다.
    """
    w = max(len(k) for k, _ in pairs) 
    return "[판독값]\n" + "\n".join(f"{k:<{w}}  {v}" for k, v in pairs)

def note(table: dict, nid: str, **fmt) -> dict :
    """안내 한 줄을 {id, text} 로 만든다. Go 의 report.Note 가 그 모양이다.

    id 를 붙이는 이유 — 받는 쪽이 「같은 안내인가」를 문구 비교가 아니라
    id 로 판정할 수 있어야 한다. 문구를 다듬으면 화면이 새 안내로 착각한다.
    """
    return {"id": nid, "text": table[nid].format(**fmt)}
  
  # BI-RADS 를 환자용 말로 바꾼다. 등급 번호를 글에 남기지 않기 위한 표다.
#
# 여기에 두는 이유 — 초음파와 맘모가 같은 척도를 쓴다. 두 곳에 베끼면
# 한쪽만 고쳐져서 같은 등급이 검사에 따라 다른 말로 나간다.
BIRADS_PLAIN = {
    "0": "추가 촬영이 필요한 상태입니다",
    "1": "특별히 눈에 띄는 부분이 없었습니다",
    "2": "양성으로 보이는 부분이 있었습니다",
    "3": "당분간 지켜보며 확인이 필요한 정도입니다",
    "4": "조직 검사를 포함한 추가 확인이 필요한 정도입니다",
    "5": "추가 확인이 시급한 정도입니다",
    "6": "이미 확인된 병변입니다",
}


def birads_plain(display) :
    """「4~5」 · 「4C」 같은 표기에서 등급 숫자를 뽑아 환자용 문장으로 바꾼다.

    구간이면 높은 쪽에 맞춘다 — 낮은 쪽으로 읽어 안심시키는 쪽이 더 위험하다.
    """
    nums = re.findall(r"[0-6]", str(display or ""))
    return BIRADS_PLAIN.get(nums[-1]) if nums else None